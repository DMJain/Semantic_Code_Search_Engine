// writeFixture writes content to root/rel, creating parent directories.
func writeFixture(t *testing.T, root, rel, content string) string {
	t.Helper()
	abs := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(abs, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return abs
}

// TestExcludedRules is the unit table for every named exclusion rule, with a
// positive (excluded) and negative (kept) path each, plus the OS-suffix,
// build-tag and import-"C" negatives the exclusion rules must keep.
func TestExcludedRules(t *testing.T) {
	cases := []struct {
		name        string
		rel         string
		content     string
		wantRule    string
		wantExclude bool
	}{
		{"vendor positive", "vendor/k8s.io/klog/klog.go", "package klog\n", "vendor", true},
		{"vendor negative", "pkg/scheduler/scheduler.go", "package scheduler\n", "", false},
		{"zz_generated positive", "pkg/foo/zz_generated.deepcopy.go", "package foo\n", "zz_generated", true},
		{"zz_generated negative", "pkg/foo/deepcopy.go", "package foo\n", "", false},
		{"pb_go positive", "pkg/foo/api.pb.go", "package foo\n", "pb_go", true},
		{"pb_go negative", "pkg/foo/pb.go", "package foo\n", "", false},
		{"testdata positive", "pkg/foo/testdata/sample.go", "package sample\n", "testdata", true},
		{"testdata negative", "pkg/foo/testing/sample.go", "package testing\n", "", false},
		{"test_go positive", "pkg/foo/foo_test.go", "package foo\n", "test_go", true},
		{"test_go negative", "pkg/foo/xtest.go", "package foo\n", "", false},
		{"client_go path positive", "staging/src/k8s.io/client-go/kubernetes/typed/core/v1/client.go", "package v1\n", "client_go_generated", true},
		{"client_go path negative", "staging/src/k8s.io/client-go/tools/cache/store.go", "package cache\n", "", false},
		{"generated header positive", "pkg/foo/client_generated.go", "// Code generated by client-gen. DO NOT EDIT.\n\npackage foo\n", "client_go_generated", true},
		{"generated header partial negative", "pkg/foo/partial.go", "// Code generated by a tool.\n\npackage foo\n", "", false},
		{"os suffix positive", "pkg/foo/thing_windows.go", "package foo\n", "build_constraint", true},
		{"os suffix negative", "pkg/foo/thing_linux.go", "package foo\n", "", false},
		{"build tag positive", "pkg/foo/tagged.go", "//go:build windows\n\npackage foo\n", "build_constraint", true},
		{"build tag negative", "pkg/foo/tagged_linux.go", "//go:build linux\n\npackage foo\n", "", false},
		{"import C positive", "pkg/foo/cgo.go", "package foo\n\nimport \"C\"\n", "build_constraint", true},
		{"plain go negative", "pkg/foo/plain.go", "package foo\n\nfunc Foo() {}\n", "", false},
	}

	root := t.TempDir()
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			abs := writeFixture(t, root, c.rel, c.content)
			rule, excluded := walk.Excluded(root, abs)
			if excluded != c.wantExclude {
				t.Fatalf("Excluded(%q) excluded = %v, want %v", c.rel, excluded, c.wantExclude)
			}
			if rule != c.wantRule {
				t.Errorf("Excluded(%q) rule = %q, want %q", c.rel, rule, c.wantRule)
			}
		})
	}
}

// TestExcludedNonGoIsNotARule proves a non-Go file is not excluded by a rule;
// it is simply not a candidate.
func TestExcludedNonGoIsNotARule(t *testing.T) {
	root := t.TempDir()
	abs := writeFixture(t, root, "vendor/README.md", "not go\n")
	if rule, excluded := walk.Excluded(root, abs); excluded || rule != "" {
		t.Fatalf("Excluded(non-go) = (%q, %v), want (\"\", false)", rule, excluded)
	}
}

// TestExcludedAcceptsRelativePath proves Excluded works with a repo-relative
// path as well as an absolute one, since the mining probe feeds it GitHub changed-file
// paths. A relative path must resolve its content rules against root, not the
// process working directory.
func TestExcludedAcceptsRelativePath(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "vendor/k8s.io/klog/klog.go", "package klog\n")
	writeFixture(t, root, "pkg/foo/cgo.go", "package foo\n\nimport \"C\"\n")
	writeFixture(t, root, "pkg/foo/plain.go", "package foo\n\nfunc Foo() {}\n")

	cases := []struct {
		rel      string
		wantRule string
		want     bool
	}{
		{"vendor/k8s.io/klog/klog.go", "vendor", true},
		{"pkg/foo/cgo.go", "build_constraint", true},
		{"pkg/foo/plain.go", "", false},
	}
	for _, c := range cases {
		rule, excluded := walk.Excluded(root, c.rel)
		if excluded != c.want || rule != c.wantRule {
			t.Errorf("Excluded(%q) = (%q, %v), want (%q, %v)", c.rel, rule, excluded, c.wantRule, c.want)
		}
	}
}

// TestBuildContextIgnoresEnvCGO proves the corpus build context stays cgo-off
// even when the process environment enables cgo, and that an import-"C" file is
// then excluded under build_constraint (D-058, D-063).
func TestBuildContextIgnoresEnvCGO(t *testing.T) {
	t.Setenv("CGO_ENABLED", "1")
	if walk.BuildContext().CgoEnabled {
		t.Fatal("BuildContext().CgoEnabled = true with CGO_ENABLED=1 in the environment, want false")
	}
	root := t.TempDir()
	abs := writeFixture(t, root, "pkg/foo/cgo.go", "package foo\n\nimport \"C\"\n")
	rule, excluded := walk.Excluded(root, abs)
	if !excluded || rule != "build_constraint" {
		t.Fatalf("Excluded(cgo) = (%q, %v), want (\"build_constraint\", true)", rule, excluded)
	}
}

// TestImportPath checks the directory-to-import-path mapping, including the
// go.work staging modules.
func TestImportPath(t *testing.T) {
	cases := []struct{ rel, want string }{
		{"pkg/scheduler/scheduler.go", "k8s.io/kubernetes/pkg/scheduler"},
		{"cmd/kubelet/app/server.go", "k8s.io/kubernetes/cmd/kubelet/app"},
		{"main.go", "k8s.io/kubernetes"},
		{"staging/src/k8s.io/client-go/tools/cache/store.go", "k8s.io/client-go/tools/cache"},
		{"staging/src/k8s.io/api/core/v1/types.go", "k8s.io/api/core/v1"},
	}
	for _, c := range cases {
		if got := walk.ImportPath(c.rel); got != c.want {
			t.Errorf("ImportPath(%q) = %q, want %q", c.rel, got, c.want)
		}
	}
}
